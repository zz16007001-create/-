/**
 * Arabic text normalization utilities for «محلي»
 */

/**
 * توحيد النصوص العربية للمقارنة والبحث:
 * - إزالة حركات التشكيل والتنوين والشدة
 * - إزالة التطويل (الكشيدة)
 * - توحيد أشكال الألف (أ، إ، آ، ٱ -> ا)
 * - توحيد الياء والألف المقصورة (ى -> ي)
 * - توحيد التاء المربوطة (ة -> ه)
 * - تحويل الأرقام المشرقية والفارسية (٠-٩ و ۰-۹) إلى أرقام لاتينية (0-9)
 */
export function normalizeAr(text: string | null | undefined): string {
  if (!text) {
    return '';
  }

  const str = String(text);

  // جدول تحويل الأرقام المشرقية والفارسية إلى أرقام إنجليزية
  const digitMap: Record<string, string> = {
    '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4',
    '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9',
    '۰': '0', '۱': '1', '۲': '2', '۳': '3', '۴': '4',
    '۵': '5', '۶': '6', '۷': '7', '۸': '8', '۹': '9',
  };

  return str
    // إزالة التشكيل (فتحة، ضمة، كسرة، سكون، تنوين، شدة)
    .replace(/[\u064B-\u065F\u0670]/g, '')
    // إزالة التطويل / الكشيدة
    .replace(/\u0640/g, '')
    // توحيد همزات الألف
    .replace(/[أإآٱ]/g, 'ا')
    // توحيد الألف المقصورة إلى ياء
    .replace(/ى/g, 'ي')
    // توحيد التاء المربوطة إلى هاء
    .replace(/ة/g, 'ه')
    // تحويل الأرقام المشرقية
    .replace(/[٠-٩۰-۹]/g, (digit) => digitMap[digit] || digit)
    .trim()
    .toLowerCase();
}
